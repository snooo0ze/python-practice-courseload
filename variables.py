# variable = a container for value (string, integer, float, boolean)
#           a variable behaves as if it was the value that it contains

#string
first_name = "Athen" #this is a string. it contains information like text.
berry = "strawberry"

#integer
age = 17 # this is an integers. they are used to represent whole numbers without a decimal point. they are very similar to strings but with numbers instead.

#float
height = 5.4 #float variables are like integers but they allow you to use decimal points

print(f"hello {first_name}") #f strings are used to embed variables inside strings
print(f"you like {berry}")
print(f"you are {age} years old")
print(f"you are {height} feet tall")